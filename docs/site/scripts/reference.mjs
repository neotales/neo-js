import { lstat, mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const declarations = new URL("../../../types/neo-js.d.ts", import.meta.url);
const coreDeclarations = new URL("../../../types/neo-js.core.d.ts", import.meta.url);
const runtimeModules = new URL("../../../crates/neo-js/src/modules.rs", import.meta.url);
const output = fileURLToPath(new URL("../src/content/docs/api", import.meta.url));
const marker = "<!-- Generated by pnpm reference:generate. Do not edit. -->";
const coreAliases = new Map([["winregistry", "win-registry"]]);

/** Wrap a declaration in a fence longer than any backtick run in its source. */
function codeBlock(code) {
	const length = Math.max(2, ...Array.from(code.matchAll(/`+/g), ([run]) => run.length));
	const fence = "`".repeat(length + 1);
	return `${fence}ts\n${code}\n${fence}`;
}

/** Get declaration text and comments without the surrounding module's indent. */
function declarationText(node, source) {
	const indent = source.text.slice(
		source.text.lastIndexOf("\n", node.getStart() - 1) + 1,
		node.getStart(),
	);
	const text = node.getFullText(source).trim();
	if (!/^[ \t]+$/.test(indent)) return text;
	return text
		.split("\n")
		.map((line) => (line.startsWith(indent) ? line.slice(indent.length) : line))
		.join("\n");
}

/** Use declaration names as headings, including default exports and overloads. */
function declarationName(node) {
	if (ts.isExportAssignment(node)) return node.isExportEquals ? "export =" : "default";
	if (ts.isExportDeclaration(node)) {
		const from = node.moduleSpecifier?.getText() ?? "this module";
		return `${node.isTypeOnly ? "Type" : "Value"} re-exports from ${from}`;
	}
	if (ts.isImportDeclaration(node)) return "Type dependencies";
	if (ts.isVariableStatement(node)) {
		return node.declarationList.declarations.map(({ name }) => name.getText()).join(", ");
	}
	return node.name?.getText() ?? "Declaration";
}

/** Render all declarations in order, including helper types and overloads. */
function renderDeclarations(nodes, source) {
	const sections = new Map();
	for (const node of nodes) {
		const name = declarationName(node);
		const existing = sections.get(name) ?? [];
		existing.push(declarationText(node, source));
		sections.set(name, existing);
	}
	return Array.from(
		sections,
		([name, definitions]) => `## ${name}\n\n${codeBlock(definitions.join("\n\n"))}`,
	).join("\n\n");
}

/** Render an adjacent module-level JSDoc comment as introductory Markdown. */
function moduleComment(node) {
	return (
		node.jsDoc
			?.map((doc) =>
				doc
					.getText()
					.slice(3, -2)
					.split("\n")
					.map((line) => line.replace(/^[ \t]*\* ?/, ""))
					.join("\n")
					.trim(),
			)
			.join("\n\n") ?? ""
	);
}

/** Render a Starlight document; JSON string quoting also works in YAML. */
function page(title, description, body) {
	return [
		"---",
		`title: ${JSON.stringify(title)}`,
		`description: ${JSON.stringify(description)}`,
		"---",
		"",
		marker,
		"",
		body,
		"",
	].join("\n");
}

/** Parse a declaration file without losing original comments or signature formatting. */
async function readDeclarations(file) {
	const input = (await readFile(file, "utf8")).replaceAll("\r\n", "\n");
	const source = ts.createSourceFile(
		"neo-js.d.ts",
		input,
		ts.ScriptTarget.Latest,
		true,
		ts.ScriptKind.TS,
	);
	if (source.parseDiagnostics.length)
		throw new Error("The neo-js declarations contain TypeScript syntax errors.");

	const modules = new Map();
	const globals = [];
	for (const node of source.statements) {
		if (ts.isModuleDeclaration(node) && ts.isStringLiteral(node.name)) {
			const match = /^neo:([a-z]+(?:[-/][a-z]+)*)$/.exec(node.name.text);
			if (!match || !node.body || !ts.isModuleBlock(node.body)) {
				throw new Error("Expected a named neo: module with a declaration body.");
			}
			const slug = match[1];
			if (modules.has(slug)) throw new Error(`Duplicate declaration module: ${node.name.text}`);
			modules.set(slug, node);
		} else {
			globals.push(node);
		}
	}
	return { source, modules, globals };
}

/** Compare built-ins to core and publish the composed CLI declarations. */
async function referencePages() {
	const { source, modules, globals } = await readDeclarations(declarations);
	const core = await readDeclarations(coreDeclarations);
	const rust = await readFile(runtimeModules, "utf8");
	// RuntimeModule::name() maps each enum variant to its canonical import name.
	const runtime = Array.from(
		rust.matchAll(/^\s*Self::\w+ => "neo:([^"]+)",\s*$/gm),
		([, slug]) => slug,
	).sort();
	const builtins = [...core.modules.keys()].filter((slug) => !coreAliases.has(slug)).sort();
	if (runtime.join() !== builtins.join()) {
		throw new Error(
			`Built-in module names and core declarations differ.\nRuntime: ${runtime.join(", ")}\nTypes: ${builtins.join(", ")}`,
		);
	}
	for (const [alias, canonical] of coreAliases) {
		const statements = core.modules.get(alias)?.body.statements;
		const declaration = statements?.[0];
		if (
			!builtins.includes(canonical) ||
			statements?.length !== 1 ||
			!declaration ||
			!ts.isExportDeclaration(declaration) ||
			declaration.isTypeOnly ||
			declaration.exportClause ||
			!declaration.moduleSpecifier ||
			!ts.isStringLiteral(declaration.moduleSpecifier) ||
			declaration.moduleSpecifier.text !== `neo:${canonical}`
		) {
			throw new Error(`Core alias neo:${alias} must re-export neo:${canonical}.`);
		}
	}
	if ([...core.modules.keys()].some((slug) => !modules.has(slug))) {
		throw new Error("The CLI declarations omit at least one core module.");
	}
	const typed = [...modules.keys()].sort();

	const pages = new Map();
	pages.set(
		"index.md",
		page(
			"API reference",
			"Globals and TypeScript declarations for the CLI's built-in and registered neo: modules.",
			[
				"The module pages reproduce the CLI exports and signatures in `types/neo-js.d.ts`, including types that do not exist at runtime. The CLI composition includes `neojs-os`, `neojs-os-user`, `neojs-schedulers`, and `neojs-sqlite`. Core alone does not provide those modules or the `os` global. See [declaration selection](/runtime/typescript/#select-declarations).",
				"A declaration does not grant access. See [Host permissions and module access](/runtime/permissions/) for permission flags, conditional exports, and module allowlists.",
				"## Globals",
				"[Public host globals](/api/globals/), including `console` and the file-only `URL` constructor.",
				"## Modules",
				typed.map((slug) => `- [\`neo:${slug}\`](/api/modules/${slug}/)`).join("\n"),
			].join("\n\n"),
		),
	);
	pages.set(
		"globals.md",
		page(
			"Public host globals",
			"Public globals added by the neo-js host.",
			[
				"This page lists the public globals added by neo-js, not QuickJS built-ins or private host callbacks.",
				"The host always installs `console`. `os` requires registration of `neojs-os` and allowlist admission of `neo:os`. `URL` requires admission of `neo:path`. Neither needs a permission flag. `env` requires `--allow-env` and admission of `neo:env`. `fs` requires `--allow-fs` and admission of `neo:fs`. See [host permissions and module access](/runtime/permissions/).",
				"## console",
				"The declaration file does not currently declare `console`. The host implements these synchronous methods and joins their string arguments with spaces before writing a line to stdout or stderr.",
				codeBlock(
					"declare const console: {\n  log(...args: string[]): void;\n  error(...args: string[]): void;\n};",
				),
				"## URL",
				"The host installs a [file-only `URL` constructor](/guides/modules/path/#file-urls). The declaration file describes it as [`FileURLConstructor`](/api/modules/path/#fileurlconstructor) without redeclaring the DOM or WebWorker global.",
				renderDeclarations(globals, source),
			].join("\n\n"),
		),
	);
	for (const slug of typed) {
		const node = modules.get(slug);
		const name = node.name.text;
		const body = [
			`Declarations for \`${name}\`. See [host permissions and module access](/runtime/permissions/) before importing.`,
			moduleComment(node),
			renderDeclarations(node.body.statements, source),
		]
			.filter(Boolean)
			.join("\n\n");
		pages.set(`modules/${slug}.md`, page(name, `TypeScript declarations for ${name}.`, body));
	}
	return pages;
}

/** Inspect the generator-owned tree without following links or accepting extra content. */
async function existingPages(pages, check) {
	const root = await lstat(output).catch((error) => {
		if (error.code === "ENOENT") return null;
		throw error;
	});
	if (!root) return new Map();
	if (!root.isDirectory())
		throw new Error("The generated API reference root must be a real directory.");

	const expectedDirectories = new Set();
	for (const name of pages.keys()) {
		const parts = name.split("/");
		for (let depth = 1; depth < parts.length; depth++) {
			expectedDirectories.add(parts.slice(0, depth).join("/"));
		}
	}

	const existing = new Map();
	const unexpected = [];
	/** Walk only expected directories. Do not follow symlinks. */
	async function inspect(prefix) {
		const entries = await readdir(join(output, prefix), { withFileTypes: true });
		for (const entry of entries) {
			const name = `${prefix}${entry.name}`;
			if (expectedDirectories.has(name)) {
				if (entry.isDirectory()) await inspect(`${name}/`);
				else unexpected.push(name);
				continue;
			}
			if (entry.isFile() && (pages.has(name) || (!check && name.endsWith(".md")))) {
				const content = (await readFile(join(output, name), "utf8")).replaceAll("\r\n", "\n");
				if (pages.has(name) || content.split("\n").includes(marker)) {
					existing.set(name, content);
					continue;
				}
			}
			unexpected.push(name);
		}
	}
	await inspect("");
	if (unexpected.length) {
		throw new Error(
			`Unexpected entries in the generated API reference: ${unexpected.sort().join(", ")}. Move handwritten files out of this directory${check ? " and run pnpm reference:generate to remove obsolete generated pages" : ""}.`,
		);
	}
	return existing;
}

/** Verify committed pages or regenerate them from the current declarations. */
async function main(args) {
	if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
		throw new Error("Usage: node scripts/reference.mjs [--check]");
	}
	const pages = await referencePages();
	const check = args[0] === "--check";
	const existing = await existingPages(pages, check);
	if (check) {
		const stale = [...pages.keys()].filter((name) => existing.get(name) !== pages.get(name));
		if (stale.length) {
			throw new Error(
				`API reference differs: ${stale.sort().join(", ")}. Run pnpm reference:generate.`,
			);
		}
		console.log(`API reference matches ${pages.size} generated pages.`);
		return;
	}

	for (const [name, content] of pages) {
		const file = join(output, name);
		await mkdir(dirname(file), { recursive: true });
		await writeFile(file, content);
	}
	for (const name of existing.keys()) {
		if (!pages.has(name)) await unlink(join(output, name));
	}
	console.log(`Generated ${pages.size} API reference pages.`);
}

try {
	await main(process.argv.slice(2));
} catch (error) {
	console.error(
		error.code ? `Could not read or write the API reference: ${error.code}.` : error.message,
	);
	process.exitCode = 1;
}
